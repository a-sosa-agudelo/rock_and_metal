            <p>Detrás de los decibelios</p>
            <h2 id="titulo-curiosidades">Curiosidades para subir el volumen</h2>
            <ul>
                <li>Freddie Mercury nació en Zanzíbar con el nombre de Farrokh Bulsara.</li>
                <li>Lemmy Kilmister solía conectar su bajo a amplificadores de guitarra para conseguir su sonido áspero y potente.</li>
                <li>La mascota de Iron Maiden, Eddie, apareció por primera vez en la portada de su álbum debut de 1980.</li>
                <li>El riff inicial de “Smoke on the Water” de Deep Purple está inspirado en un incendio real ocurrido durante un concierto de Frank Zappa en Montreux, Suiza, en 1971.</li>
                <li>El álbum en directo “Live at Wembley ’86” captura uno de los conciertos más célebres de Queen, con Freddie Mercury al frente del estadio.</li>
            </ul>
