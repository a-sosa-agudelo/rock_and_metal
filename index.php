        <section id="historia" aria-labelledby="titulo-historia">
            <p>El volumen sube</p>
            <h2 id="titulo-historia">De los clubes al rugido de los estadios</h2>
            <p>El rock y el metal no aparecieron de la nada: nacieron de cruces de culturas, guitarras amplificadas y artistas dispuestos a llevar el sonido un paso más lejos.</p>

            <article>
                <h3>Años 50 · La electricidad toma el mando</h3>
                <p>El rock and roll sacude la radio con ritmos intensos y guitarras al frente. Chuck Berry convierte cada solo en una declaración y ayuda a definir el lenguaje de toda una generación de músicos.</p>
            </article>
            <article>
                <h3>Años 60 · El escenario se vuelve laboratorio</h3>
                <p>La experimentación sonora y los conciertos cada vez más potentes empujan los límites. Jimi Hendrix transforma la guitarra eléctrica en una fuerza expresiva y demuestra que un amplificador también puede ser parte del espectáculo.</p>
            </article>
            <article>
                <h3>Años 70 · Nace una nueva fuerza</h3>
                <p>En Birmingham, Black Sabbath publica su álbum debut en 1970 con un sonido oscuro y contundente. La potencia de los amplificadores, los riffs pesados y la presencia escénica abren un camino que pronto conquistará escenarios de todo el mundo.</p>
            </article>
            <article>
                <h3>Años 80 · Himnos para cantar a pleno pulmón</h3>
                <p>Grandes giras, discos de enorme alcance y una identidad visual inolvidable convierten a bandas como Iron Maiden, Metallica y Motörhead en nombres esenciales de la cultura popular.</p>
            </article>
            <article>
                <h3>De los 90 hasta hoy · El legado sigue vivo</h3>
                <p>Nuevas generaciones recogen el testigo, llenan festivales y mantienen viva la energía del directo. El rock y el metal siguen creciendo porque cada época encuentra su propia manera de hacer ruido.</p>
            </article>
        </section>

